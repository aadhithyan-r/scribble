export const CURATED_WORDS_BY_CATEGORY: Readonly<
  Record<CuratedCategoryId, readonly string[]>
> = Object.fromEntries(
  CURATED_CATEGORIES.map((category) => [category.id, category.words]),
) as Record<CuratedCategoryId, readonly string[]>;

export const CURATED_WORD_POOL: readonly string[] = CURATED_CATEGORIES.flatMap(
  (category) => category.words,
);

export const CURATED_WORD_COUNT = CURATED_WORD_POOL.length;

export const isCuratedCategoryId = (value: unknown): value is CuratedCategoryId =>
  typeof value === "string" &&
  (CURATED_CATEGORY_IDS as readonly string[]).includes(value);
